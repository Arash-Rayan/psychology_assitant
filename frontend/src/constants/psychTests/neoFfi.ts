function domainForItemNumber(n: number): string {
  return DOMAIN_KEYS[(n - 1) % 5];
}

const NEO_QUESTIONS: PsychTestQuestion[] = NEO_ITEM_TEXTS.map((text, index) => {
  const number = index + 1;
  return {
    id: `neo${number}`,
    text: `${number}. ${text}`,
    domain: domainForItemNumber(number),
    reverseScored: NEO_REVERSE_ITEMS.has(number),
  };
});

export const NEO_FFI_TEST: PsychTestDefinition = {
  id: 'neo_ffi',
  title: 'تست نئو (NEO-FFI)',
  subtitle: 'پنج‌عاملی شخصیت — ۶۰ سوال',
  description:
    '۶۰ جملهٔ NEO-FFI (فرم کوتاه). میزان موافقت خود را از «کاملاً مخالفم» تا «کاملاً موافقم» علامت بزنید. به رفتار و احساس معمول خود فکر کنید، نه آرزوهایتان.',
  options: NEO_OPTIONS,
  questions: NEO_QUESTIONS,
  score(answers) {
    const domainScores = DOMAIN_KEYS.map((key) => {
      const items = NEO_QUESTIONS.filter((q) => q.domain === key);
      let sum = 0;
      for (const item of items) {
        const raw = answers[item.id] ?? 3;
        sum += item.reverseScored ? 6 - raw : raw;
      }
      const max = items.length * 5;
      return { key, label: DOMAIN_LABELS[key] ?? key, score: sum, max };
    });

    const totalScore = domainScores.reduce((s, d) => s + d.score, 0);
    const maxScore = domainScores.reduce((s, d) => s + d.max, 0);
    const domainText = domainScores.map((d) => `${d.label}: ${d.score} از ${d.max}`).join(' · ');

    return {
      totalScore,
      maxScore,
      domains: domainScores,
      interpretation: `پروفایل پنج‌عاملی: ${domainText}. این نمرات بر اساس کلید نمره‌دهی استاندارد NEO-FFI محاسبه شده‌اند.`,
    };
  },
};
