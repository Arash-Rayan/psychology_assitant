export const BDI2_TEST: PsychTestDefinition = {
  id: 'bdi2',
  title: 'تست افسردگی بک (BDI-II)',
  subtitle: 'پرسشنامهٔ افسردگی بک — ویرایش دوم',
  description:
    '۲۱ گروه جمله بر اساس BDI-II. در هر گروه جمله‌ای را انتخاب کنید که احساس شما در دو هفتهٔ گذشته (شامل امروز) را بهتر بیان کند. اگر چند جمله درست به نظر می‌رسد، جمله‌ای با نمرهٔ بالاتر را انتخاب کنید.',
  questions: BDI_QUESTIONS,
  score(answers) {
    const total = Object.values(answers).reduce((sum, v) => sum + v, 0);
    const maxScore = 63;
    const { label, text } = interpretBdi(total);
    return {
      totalScore: total,
      maxScore,
      severityLabel: label,
      interpretation: `نمرهٔ کل: ${total} از ${maxScore}. سطح: ${label}. ${text}`,
    };
  },
};
