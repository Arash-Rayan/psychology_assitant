import type { LikertOption, PsychTestDefinition, PsychTestQuestion } from './types';

/** BDI-II — ترجمهٔ فارسی رایج (BDI-II-PERSIAN / منابع بالینی ایرانی) */
function bdiItem(
  id: string,
  title: string,
  statements: [string, string, string, string],
): PsychTestQuestion {
  const options: LikertOption[] = statements.map((label, value) => ({ value, label }));
  return { id, text: title, options };
}

function interpretBdi(total: number): { label: string; text: string } {
  if (total <= 13) {
    return { label: 'حداقل', text: 'نشانه‌های افسردگی در محدودهٔ حداقل گزارش شده است.' };
  }
  if (total <= 19) {
    return { label: 'خفیف', text: 'نشانه‌های افسردگی خفیف — پیگیری بالینی توصیه می‌شود.' };
  }
  if (total <= 28) {
    return { label: 'متوسط', text: 'نشانه‌های افسردگی متوسط — ارزیابی تخصصی توصیه می‌شود.' };
  }
  return { label: 'شدید', text: 'نشانه‌های افسردگی شدید — ارزیابی فوری توسط درمانگر ضروری است.' };
}

