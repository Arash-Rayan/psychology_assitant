export function getPublicDoctorBySlug(slug: string): PublicDoctor | undefined {
  return PUBLIC_DOCTORS.find((d) => d.slug === slug);
}

export function getDoctorBlog(
  doctorSlug: string,
  blogSlug: string,
): { doctor: PublicDoctor; blog: PublicDoctor['blogs'][number] } | undefined {
  const doctor = getPublicDoctorBySlug(doctorSlug);
  if (!doctor) return undefined;
  const blog = doctor.blogs.find((b) => b.slug === blogSlug);
  if (!blog) return undefined;
  return { doctor, blog };
}
